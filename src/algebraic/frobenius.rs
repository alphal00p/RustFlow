//! Restriction of scalars for registered square-root endpoint expansions.
//!
//! For each root monomial m_S = product_{i in S} r_i, adjoin m_S Y.
//! Multiplication uses r_i^2 = R_i and differentiation adds
//! sum_{i in S} R_i'/(2 R_i) on the diagonal. This is an exact rational
//! connection, so the existing Frobenius engine supplies powers, logarithms,
//! resonances and coupled blocks. No second algebra or series engine is needed.
